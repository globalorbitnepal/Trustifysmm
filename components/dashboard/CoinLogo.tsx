export function coinKey(code: string): string {
  const key = (code || "").toLowerCase();
  if (COIN_KEYS[key]) return COIN_KEYS[key];
  const prefix = Object.keys(COIN_KEYS)
    .sort((a, b) => b.length - a.length)
    .find((candidate) => key.startsWith(candidate));
  return prefix ? COIN_KEYS[prefix] : "";
}

export function coinColor(code: string): string {
  const key = coinKey(code);
  if (key === "usdc") return USDC.hex;
  const entry = COINS[key];
  return entry?.hex ?? "#7c6cf5";
}

export function COIN_SYMBOL(code: string) {
  const key = coinKey(code);
  return key ? key.toUpperCase() : code.toUpperCase();
}

/**
 * Coin logo. Uses the provider logo when the URL is a relative NOWPayments asset,
 * otherwise a verified brand path from simple-icons. Never falls back to an emoji.
 */
export function CoinLogo({
  code,
  size = 40,
  className,
  style,
}: {
  code: string;
  size?: number;
  className?: string;
  style?: CSSProperties;
}) {
  const key = coinKey(code);
  const color = coinColor(code);
  const boxStyle: CSSProperties = {
    width: size,
    height: size,
    borderRadius: size / 2,
    display: "inline-grid",
    placeItems: "center",
    flexShrink: 0,
    background: `${color}1f`,
    border: `1px solid ${color}59`,
    ...style,
  };

  if (key === "usdc") {
    return (
      <span className={className} style={boxStyle} aria-hidden>
        <svg viewBox="0 0 24 24" width={size * 0.72} height={size * 0.72}>
          <path d={USDC.path} fill={USDC.hex} />
        </svg>
      </span>
    );
  }

  const entry = COINS[key];
  if (!entry) {
    return (
      <span className={className} style={boxStyle} aria-hidden>
        <span style={{ fontSize: size * 0.32, fontWeight: 800, color }}>{code.slice(0, 4).toUpperCase()}</span>
      </span>
    );
  }

  return (
    <span className={className} style={boxStyle} aria-hidden>
      <svg viewBox="0 0 24 24" width={size * 0.66} height={size * 0.66}>
        <path d={entry.path} fill={entry.hex} />
      </svg>
    </span>
  );
}